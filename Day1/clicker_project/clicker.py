# Импортируем библиотеку tkinter для создания графического интерфейса
import tkinter as tk


# Функция для чтения данных из файла data.txt
def file_data():
    # Открываем файл и читаем все строки
    with open("data.txt") as f:
        data = f.readlines()  # Получаем список строк

        int_data = []  # Создаём пустой список, куда будем складывать числа

        # Преобразуем каждую строку в число и добавляем в список
        for num in data:
            int_data.append(int(num.rstrip()))  # Убираем перенос строки и переводим в int

    return int_data  # Возвращаем список чисел (x, y, z)


# Функция для записи новых значений в файл data.txt
def write_data(x, y, z):
    with open("data.txt", "w") as f:  # Открываем файл на запись (старое содержимое удаляется)
        string = f"{x}\n{y}\n{z}"  # Делаем строку из трёх чисел через перенос строки
        f.write(string)  # Записываем эту строку в файл


# Читаем данные из файла
# Первый элемент — рекорд (max_score)
max_score = file_data()[0]

# Получаем все три значения из файла
x, y, z = file_data()

# Обнуляем значение кликов (y), но не сохраняем его пока в файл
write_data(x, 0, z)  # Записываем x=рекорд, y=0, z=сколько всего кликов


# Функция, которая вызывается при нажатии на кнопку
def click():
    # Снова читаем данные из файла
    x, y, z = file_data()

    # Увеличиваем количество кликов (y и z)
    y += 1  # Текущая серия кликов
    z += 1  # Общее количество кликов за всё время

    # Проверяем, побил ли пользователь рекорд
    if y > x:
        x = y  # Новый рекорд!
        # Меняем текст метки "Рекорд"
        max_score_lbl.config(
            text=f"Рекорд:\n{x}"
        )

    # Меняем текст метки "Количество кликов"
    score_view.config(
        text=f"Количество кликов:\n{y}"
    )

    # Сохраняем новые значения в файл
    write_data(x, y, z)


# Создаем главное окно приложения
root = tk.Tk()
root.title("Кликер")  # Заголовок окна
root.geometry("900x600")  # Размер окна
root.config(bg="#FFD9DA")  # Цвет фона окна (нежно-розовый)

# Метка (надпись), которая показывает текущее количество кликов
score_view = tk.Label(root,
                      text="Количество кликов:\n0",  # Текст по умолчанию
                      bg="#2A2A2A",  # Цвет фона (темно-серый)
                      fg="#FFF",  # Цвет текста (белый)
                      font=("Montserrat Thin", 60)  # Шрифт и размер
                      )
score_view.pack()  # Размещаем надпись в окне

# Метка, которая показывает рекорд
max_score_lbl = tk.Label(root,
                         text=f"Рекорд\n{max_score}",  # Выводим текущий рекорд
                         bg="#3A3A3A",  # Цвет фона (немного светлее)
                         fg="#FFF",
                         font=("Montserrat Thin", 50)
                         )
max_score_lbl.pack()  # Размещаем надпись

# Кнопка, которую можно нажимать
click_btn = tk.Button(root,
                      text="Жми!",  # Текст на кнопке
                      command=click,  # Какая функция выполняется при клике
                      bg="#30343F",  # Цвет кнопки
                      fg="#FFF",  # Цвет текста
                      font=("Montserrat Black", 40),  # Шрифт и размер
                      activebackground="#10141F",  # Цвет при нажатии
                      activeforeground="#FFF"  # Цвет текста при нажатии
                      )
click_btn.pack()  # Размещаем кнопку

# Запускаем главный цикл приложения — окно будет работать, пока мы его не закроем
root.mainloop()
